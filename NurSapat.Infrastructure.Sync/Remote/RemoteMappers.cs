        OrderNumber = o.OrderNumber ?? string.Empty,
        OrderDate = o.OrderDate,
        Status = o.Status,
        CustomerId = o.CustomerId,
        DealerId = o.DealerId,
        CurrentPriceMode = o.CurrentPriceMode,
